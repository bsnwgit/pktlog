/**
 * Returns the full protocol name for a given IANA protocol number.
 * Fallback: "Protocol N"
 */
export function protoLabel(n: number): string {
  return PROTO_NAMES[n] ?? `Protocol ${n}`
}

/**
 * Returns a short/abbreviated protocol name (same as protoLabel, kept separate
 * for future use if display space is constrained).
 */
export function protoShort(n: number): string {
  return PROTO_NAMES[n] ?? `Proto ${n}`
}
